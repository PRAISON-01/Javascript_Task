let number = Math.floor(Math.random() * 7) + 1;
let color;

switch (number) {
    case 1: color = "Red";
    break;
    case 2: color = "Orange"; 
    break;
    case 3: color = "Yellow"; 
    break;
    case 4: color = "Green"; 
    break;
    case 5: color = "Blue"; 
    break;
    case 6: color = "Indigo"; 
    break;
    case 7: color = "Violet"; 
    break;
    default: color = "Unknown";
}

